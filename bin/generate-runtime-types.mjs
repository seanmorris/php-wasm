#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const runtimePackages = ['php-wasm', 'php-cli-wasm', 'php-cgi-wasm', 'php-dbg-wasm', 'php-cloud-wasm', 'php-sdl-wasm'];

// Handwritten ESM declarations are authoritative. CJS declarations must name
// their declaration dependencies explicitly: .js resolves to .d.ts, not .d.cts.
export async function generateRuntimeTypes(root = repoRoot, {check = false} = {})
{
	async function output(filename, contents)
	{
		if(check)
		{
			if(await fs.readFile(filename, 'utf8').catch(() => '') !== contents)
				throw new Error(`Stale runtime types: ${filename}; run npm run generate:types`);
		}
		else await fs.writeFile(filename, contents);
	}
	for(const name of runtimePackages)
	{
		const directory = path.join(root, 'packages', name);
		const filename = path.join(directory, 'package.json');
		const pkg = JSON.parse(await fs.readFile(filename, 'utf8'));
		const commonjs = !['php-cloud-wasm', 'php-sdl-wasm'].includes(name);
		for(const declaration of (await fs.readdir(directory)).filter(file => /^Php.*\.d\.mts$/.test(file)).sort())
		{
			const entry = declaration.replace('.d.mts', '');
			const esm = {types: `./${entry}.d.mts`, default: `./${entry}.mjs`};
			const cjs = {types: `./${entry}.d.cts`, default: `./${entry}.js`};
			const mapping = commonjs
				? {import: esm, require: cjs, default: `./${entry}.mjs`}
				: {types: esm.types, import: esm.default, default: esm.default};
			pkg.exports[`./${entry}`] = mapping;
			pkg.exports[`./${entry}.mjs`] = {types: esm.types, default: esm.default};
			if(pkg.main === cjs.default)
			{
				pkg.exports['.'] = mapping;
				pkg.types = cjs.types;
			}
			if(commonjs)
			{
				pkg.exports[`./${entry}.js`] = cjs;
				const source = await fs.readFile(path.join(directory, declaration), 'utf8');
				const contents = source.replace(/(from\s+|import\()['"]\.\/([^'"]+)\.mjs['"]/g, "$1'./$2.d.cts'");
				await output(path.join(directory, `${entry}.d.cts`), `// Generated by bin/generate-runtime-types.mjs.\n${contents}`);
			}
		}
		if(commonjs && !pkg.files.includes('*.d.cts')) pkg.files.push('*.d.cts');
		if(name === 'php-dbg-wasm') pkg.exports['./public'] = {types: './public.d.ts', default: './public.d.ts'};
		await output(filename, `${JSON.stringify(pkg, null, 2)}\n`);
	}
}

if(process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
	await generateRuntimeTypes(repoRoot, {check: process.argv.includes('--check')});
